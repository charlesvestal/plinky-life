#!/bin/sh
# plinky-life - produce the single .cpp that gets flashed.
#
# Panel code cannot use #include, so the pure headers under src/ are spliced in
# ahead of panel.cpp. The metadata block comment must be the FIRST thing in the
# file, so it is lifted off panel.cpp and re-emitted at the top.
#
# Output: plinky_life.cpp
set -e
cd "$(dirname "$0")/.."

OUT=plinky_life.cpp
HEADERS="src/life.h src/selection.h src/traversal.h src/scales.h src/voice.h src/ccmap.h src/chance.h src/spark.h"

# 1. the metadata block comment, which must lead the file
awk 'NR==1 && $0!="/*" { print "amalgamate: panel.cpp must start with the metadata comment" > "/dev/stderr"; exit 1 }
     { print }
     /^\*\/$/ { exit }' src/panel.cpp > "$OUT"

printf '\n/* Generated by build/amalgamate.sh - do not edit. Edit the src/ headers and src/panel.cpp. */\n\n' >> "$OUT"

# 2. the pure logic headers
for h in $HEADERS; do
    printf '/* ===== %s ===== */\n' "$h" >> "$OUT"
    cat "$h" >> "$OUT"
    printf '\n' >> "$OUT"
done

# 3. panel.cpp with its metadata comment stripped
printf '/* ===== src/panel.cpp ===== */\n' >> "$OUT"
awk 'skip && /^\*\/$/ { skip=0; next } skip { next } NR==1 && $0=="/*" { skip=1; next } { print }' \
    src/panel.cpp >> "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines, $(wc -c < "$OUT" | tr -d ' ') bytes)"
